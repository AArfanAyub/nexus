/**
 * Dev-only key material generator.
 *
 *   node scripts/gen-license-keys.mjs [--force]
 *
 * Writes:
 *   keys/private.pem              (gitignored — never commit, never ship)
 *   src/main/license/pubkey.ts    (committed — a public key is public, and CI
 *                                  must be able to build without the private half)
 *
 * The public key is embedded as a PEM string so `license/verify.ts` needs no
 * filesystem access at runtime.
 */

import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const keysDir = path.join(root, 'keys');
const privatePath = path.join(keysDir, 'private.pem');
const pubkeyTsPath = path.join(root, 'src', 'main', 'license', 'pubkey.ts');

const force = process.argv.includes('--force');

if (existsSync(privatePath) && !force) {
  process.stdout.write(
    `refusing to overwrite ${privatePath}\n` +
      'existing keys would invalidate every key already issued.\n' +
      're-run with --force only if you intend to invalidate them.\n',
  );
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519');

const privatePem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const publicPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();

mkdirSync(keysDir, { recursive: true });
writeFileSync(privatePath, privatePem, { encoding: 'utf8', mode: 0o600 });

const header =
  '/* Copyright (c) 2026 arfanayub0. All rights reserved. Licensed under the NEXUS Proprietary Perpetual License. See LICENSE. */';
const body = `${header}

/**
 * GENERATED by \`scripts/gen-license-keys.mjs\` — do not edit by hand.
 *
 * Ed25519 public key (SPKI, PEM) used by \`license/verify.ts\`. Committed on
 * purpose: verification only needs the public half, and a build must never
 * depend on \`keys/private.pem\` being present (decision D-10).
 */
export const LICENSE_PUBLIC_KEY_PEM: string = ${JSON.stringify(publicPem)};
`;

mkdirSync(path.dirname(pubkeyTsPath), { recursive: true });
writeFileSync(pubkeyTsPath, body, 'utf8');

process.stdout.write(`wrote ${privatePath}\nwrote ${pubkeyTsPath}\n`);
process.stdout.write(`\npublic key fingerprint:\n${publicPem}`);
